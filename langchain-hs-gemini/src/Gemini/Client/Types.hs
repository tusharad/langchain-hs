-- | Multimodal content part.
data Content
  = TextContent !Text
  | -- | mime_type, base64 data
    ImageContent !Text !Text
  | -- | mime_type, base64 data
    AudioContent !Text !Text
  | -- | mime_type, base64 data
    DocumentContent !Text !Text
  deriving (Eq, Show, Generic)

instance ToJSON Content where
  toJSON = \case
    TextContent txt ->
      object ["type" .= ("text" :: Text), "text" .= txt]
    ImageContent mime b64 ->
      object ["type" .= ("image" :: Text), "mime_type" .= mime, "data" .= b64]
    AudioContent mime b64 ->
      object ["type" .= ("audio" :: Text), "mime_type" .= mime, "data" .= b64]
    DocumentContent mime b64 ->
      object ["type" .= ("document" :: Text), "mime_type" .= mime, "data" .= b64]

instance FromJSON Content where
  parseJSON = withObject "Content" $ \o -> do
    t <- o .: "type"
    case (t :: Text) of
      "text" -> TextContent <$> o .: "text"
      "image" -> ImageContent <$> o .: "mime_type" <*> o .: "data"
      "audio" -> AudioContent <$> o .: "mime_type" <*> o .: "data"
      "document" -> DocumentContent <$> o .: "mime_type" <*> o .: "data"
      other -> fail $ "Unknown Content type: " ++ T.unpack other

