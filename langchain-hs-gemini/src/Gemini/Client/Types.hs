-- | Built-in or custom tool declared for the model.
data Tool
  = FunctionTool
      { functionName :: !Text
      , functionDescription :: !(Maybe Text)
      , functionParameters :: !(Maybe Value)
      }
  | GoogleSearchTool
  | GoogleMapsTool
      { mapsLatitude :: !(Maybe Double)
