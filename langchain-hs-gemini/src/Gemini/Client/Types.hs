-- | Flexible input format for Interaction creation.
data InteractionsInput
  = TextInput !Text
  | ContentInput !Content
  | ContentListInput ![Content]
  | StepListInput ![Step]
  deriving (Eq, Show, Generic)

instance ToJSON InteractionsInput where
  toJSON = \case
    TextInput t -> toJSON t
    ContentInput c -> toJSON c
    ContentListInput cs -> toJSON cs
    StepListInput ss -> toJSON ss

instance FromJSON InteractionsInput where
  parseJSON v = case v of
    String s -> pure $ TextInput s
    Array arr ->
      (StepListInput <$> parseJSON (Array arr))
        <|> (ContentListInput <$> parseJSON (Array arr))
    Object _ -> ContentInput <$> parseJSON v
    _ -> fail "Invalid InteractionsInput format"

