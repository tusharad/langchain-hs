-- | Single step within an interaction turn.
data Step
  = UserInputStep ![Content]
  | ModelOutputStep ![Content]
  | FunctionCallStep
      { callName :: !Text
      , callArguments :: !Value
      , callId :: !Text
      }
  | FunctionResultStep
      { resultCallId :: !Text
      , resultName :: !(Maybe Text)
      , resultPayload :: !Value
      , resultIsError :: !(Maybe Bool)
      }
  | ThoughtStep
      { thoughtSignature :: !(Maybe Text)
      , thoughtSummary :: !(Maybe [Content])
      }
  | CodeExecutionCallStep
      { codeCallId :: !Text
      , codeCallCode :: !Text
      , codeCallSignature :: !(Maybe Text)
      }
  | CodeExecutionResultStep
      { codeResultCallId :: !Text
      , codeResultOutput :: !Text
      , codeResultIsError :: !(Maybe Bool)
      }
  | GoogleSearchCallStep
      { searchCallId :: !Text
      , searchQuery :: !Text
      , searchType :: !(Maybe Text)
      }
  | GoogleSearchResultStep
      { searchResultCallId :: !Text
      , searchResultItems :: ![GoogleSearchResultItem]
      }
  | GoogleMapsCallStep
      { mapsCallId :: !Text
      , mapsQuery :: !(Maybe Text)
      }
  | GoogleMapsResultStep
      { mapsResultCallId :: !Text
      , mapsResultPayload :: !(Maybe Value)
      }
  | FileSearchCallStep
      { fileSearchCallId :: !Text
      , fileSearchQuery :: !(Maybe Text)
      }
  | FileSearchResultStep
      { fileSearchResultCallId :: !Text
      , fileSearchResultPayload :: !(Maybe Value)
      }
  | UrlContextCallStep
      { urlCallId :: !Text
      , urlQuery :: !(Maybe Text)
      }
  | UrlContextResultStep
      { urlResultCallId :: !Text
      , urlResultPayload :: !(Maybe Value)
      }
  deriving (Eq, Show, Generic)

-- | Google Search result snippet.
data GoogleSearchResultItem = GoogleSearchResultItem
  { searchTitle :: !(Maybe Text)
  , searchUrl :: !(Maybe Text)
  , searchSnippet :: !(Maybe Text)
  }
  deriving (Eq, Show, Generic)

instance FromJSON GoogleSearchResultItem where
  parseJSON = withObject "GoogleSearchResultItem" $ \o -> do
    searchTitle <- o .:? "title"
    searchUrl <- o .:? "url"
    searchSnippet <- o .:? "snippet"
    pure GoogleSearchResultItem {..}

instance ToJSON GoogleSearchResultItem where
  toJSON GoogleSearchResultItem {..} =
    object $
      catMaybes
        [ ("title" .=) <$> searchTitle
        , ("url" .=) <$> searchUrl
        , ("snippet" .=) <$> searchSnippet
        ]

instance ToJSON Step where
  toJSON = \case
    UserInputStep cs ->
      object ["type" .= ("user_input" :: Text), "content" .= cs]
    ModelOutputStep cs ->
      object ["type" .= ("model_output" :: Text), "content" .= cs]
    FunctionCallStep {..} ->
      object
        [ "type" .= ("function_call" :: Text)
        , "name" .= callName
        , "arguments" .= callArguments
        , "id" .= callId
        ]
    FunctionResultStep {..} ->
      object $
        [ "type" .= ("function_result" :: Text)
        , "call_id" .= resultCallId
        , "result" .= resultPayload
        ]
          ++ catMaybes
            [ ("name" .=) <$> resultName
            , ("is_error" .=) <$> resultIsError
            ]
    ThoughtStep {..} ->
      object $
        ("type" .= ("thought" :: Text))
          : catMaybes
            [ ("signature" .=) <$> thoughtSignature
            , ("summary" .=) <$> thoughtSummary
            ]
    CodeExecutionCallStep {..} ->
      object $
        [ "type" .= ("code_execution_call" :: Text)
        , "id" .= codeCallId
        , "arguments" .= object ["code" .= codeCallCode]
        ]
          ++ catMaybes [("signature" .=) <$> codeCallSignature]
    CodeExecutionResultStep {..} ->
      object $
        [ "type" .= ("code_execution_result" :: Text)
        , "call_id" .= codeResultCallId
        , "result" .= codeResultOutput
        ]
          ++ catMaybes [("is_error" .=) <$> codeResultIsError]
    GoogleSearchCallStep {..} ->
      object $
        [ "type" .= ("google_search_call" :: Text)
        , "id" .= searchCallId
        , "arguments" .= object ["query" .= searchQuery]
        ]
          ++ catMaybes [("search_type" .=) <$> searchType]
    GoogleSearchResultStep {..} ->
      object
        [ "type" .= ("google_search_result" :: Text)
        , "call_id" .= searchResultCallId
        , "result" .= searchResultItems
        ]
    GoogleMapsCallStep {..} ->
      object $
        ("type" .= ("google_maps_call" :: Text))
          : ("id" .= mapsCallId)
          : catMaybes [("query" .=) <$> mapsQuery]
    GoogleMapsResultStep {..} ->
      object $
        ("type" .= ("google_maps_result" :: Text))
          : ("call_id" .= mapsResultCallId)
          : catMaybes [("result" .=) <$> mapsResultPayload]
    FileSearchCallStep {..} ->
      object $
        ("type" .= ("file_search_call" :: Text))
          : ("id" .= fileSearchCallId)
          : catMaybes [("query" .=) <$> fileSearchQuery]
    FileSearchResultStep {..} ->
      object $
        ("type" .= ("file_search_result" :: Text))
          : ("call_id" .= fileSearchResultCallId)
          : catMaybes [("result" .=) <$> fileSearchResultPayload]
    UrlContextCallStep {..} ->
      object $
        ("type" .= ("url_context_call" :: Text))
          : ("id" .= urlCallId)
          : catMaybes [("query" .=) <$> urlQuery]
    UrlContextResultStep {..} ->
      object $
        ("type" .= ("url_context_result" :: Text))
          : ("call_id" .= urlResultCallId)
          : catMaybes [("result" .=) <$> urlResultPayload]

instance FromJSON Step where
  parseJSON = withObject "Step" $ \o -> do
    t <- o .: "type"
    case (t :: Text) of
      "user_input" -> UserInputStep <$> (o .:? "content" .!= [])
      "model_output" -> ModelOutputStep <$> (o .:? "content" .!= [])
      "function_call" -> do
        callName <- o .: "name"
        callArguments <- o .:? "arguments" .!= object []
        callId <- o .:? "id" .!= ""
        pure FunctionCallStep {..}
      "function_result" -> do
        resultCallId <- o .: "call_id"
        resultName <- o .:? "name"
        resultPayload <- o .: "result"
        resultIsError <- o .:? "is_error"
        pure FunctionResultStep {..}
      "thought" -> do
        thoughtSignature <- o .:? "signature"
        thoughtSummary <- o .:? "summary"
        pure ThoughtStep {..}
      "code_execution_call" -> do
        codeCallId <- o .:? "id" .!= ""
        args <- o .:? "arguments" .!= object []
        codeCallCode <- case args of
          Object ao -> ao .:? "code" .!= ""
          _ -> pure ""
        codeCallSignature <- o .:? "signature"
        pure CodeExecutionCallStep {..}
      "code_execution_result" -> do
        codeResultCallId <- o .: "call_id"
        codeResultOutput <- o .:? "result" .!= ""
        codeResultIsError <- o .:? "is_error"
        pure CodeExecutionResultStep {..}
      "google_search_call" -> do
        searchCallId <- o .:? "id" .!= ""
        args <- o .:? "arguments" .!= object []
        searchQuery <- case args of
          Object ao -> ao .:? "query" .!= ""
          _ -> pure ""
        searchType <- o .:? "search_type"
        pure GoogleSearchCallStep {..}
      "google_search_result" -> do
        searchResultCallId <- o .: "call_id"
        searchResultItems <- o .:? "result" .!= []
        pure GoogleSearchResultStep {..}
      "google_maps_call" -> do
        mapsCallId <- o .:? "id" .!= ""
        mapsQuery <- o .:? "query"
        pure GoogleMapsCallStep {..}
      "google_maps_result" -> do
        mapsResultCallId <- o .: "call_id"
        mapsResultPayload <- o .:? "result"
        pure GoogleMapsResultStep {..}
      "file_search_call" -> do
        fileSearchCallId <- o .:? "id" .!= ""
        fileSearchQuery <- o .:? "query"
        pure FileSearchCallStep {..}
      "file_search_result" -> do
        fileSearchResultCallId <- o .: "call_id"
        fileSearchResultPayload <- o .:? "result"
        pure FileSearchResultStep {..}
      "url_context_call" -> do
        urlCallId <- o .:? "id" .!= ""
        urlQuery <- o .:? "query"
        pure UrlContextCallStep {..}
      "url_context_result" -> do
        urlResultCallId <- o .: "call_id"
        urlResultPayload <- o .:? "result"
        pure UrlContextResultStep {..}
      other -> fail $ "Unknown Step type: " ++ T.unpack other

