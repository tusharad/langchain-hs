  | ThoughtSignatureDelta !Text
  | OtherDelta !Text !Value
  deriving (Eq, Show, Generic)

instance FromJSON StepDeltaData where
  parseJSON = withObject "StepDeltaData" $ \o -> do
    t <- o .: "type"
    case (t :: Text) of
      "text" -> TextDelta <$> o .: "text"
      "arguments" -> ArgumentsDelta <$> o .: "arguments"
      "thought_signature" -> ThoughtSignatureDelta <$> o .: "signature"
      other -> pure $ OtherDelta other (Object o)

instance ToJSON StepDeltaData where
  toJSON = \case
    TextDelta txt -> object ["type" .= ("text" :: Text), "text" .= txt]
    ArgumentsDelta args -> object ["type" .= ("arguments" :: Text), "arguments" .= args]
    ThoughtSignatureDelta sig -> object ["type" .= ("thought_signature" :: Text), "signature" .= sig]
    OtherDelta _ val -> val

-- | SSE event types dispatched on the interaction stream.
data InteractionSseEvent
  = SseInteractionCreated !Interaction
  | SseInteractionStatusUpdate !Text !InteractionStatus
  | SseStepStart !Int !Step
  | SseStepDelta !Int !StepDeltaData
  | SseStepStop !Int
  | SseInteractionCompleted !Interaction
  | SseError !Text !Text
  | SseOther !Text !Value
  deriving (Eq, Show, Generic)

instance FromJSON InteractionSseEvent where
  parseJSON = withObject "InteractionSseEvent" $ \o -> do
    evType <- o .: "event_type"
    case (evType :: Text) of
      "interaction.created" -> SseInteractionCreated <$> o .: "interaction"
      "interaction.completed" -> SseInteractionCompleted <$> o .: "interaction"
      "interaction.status_update" ->
        SseInteractionStatusUpdate <$> o .: "interaction_id" <*> o .: "status"
      "step.start" -> SseStepStart <$> o .: "index" <*> o .: "step"
      "step.delta" -> SseStepDelta <$> o .: "index" <*> o .: "delta"
      "step.stop" -> SseStepStop <$> o .: "index"
      "error" -> do
        errObj <- o .: "error"
        c <- errObj .:? "code" .!= ""
        m <- errObj .:? "message" .!= ""
        pure $ SseError c m
      other -> pure $ SseOther other (Object o)

instance ToJSON InteractionSseEvent where
  toJSON = \case
    SseInteractionCreated inter ->
      object ["event_type" .= ("interaction.created" :: Text), "interaction" .= inter]
    SseInteractionCompleted inter ->
      object ["event_type" .= ("interaction.completed" :: Text), "interaction" .= inter]
    SseInteractionStatusUpdate iid st ->
      object
        ["event_type" .= ("interaction.status_update" :: Text), "interaction_id" .= iid, "status" .= st]
    SseStepStart idx step ->
      object ["event_type" .= ("step.start" :: Text), "index" .= idx, "step" .= step]
    SseStepDelta idx d ->
      object ["event_type" .= ("step.delta" :: Text), "index" .= idx, "delta" .= d]
    SseStepStop idx ->
      object ["event_type" .= ("step.stop" :: Text), "index" .= idx]
    SseError code msg ->
      object ["event_type" .= ("error" :: Text), "error" .= object ["code" .= code, "message" .= msg]]
    SseOther ev val -> case val of
      Object o -> Object (KM.insert "event_type" (String ev) o)
      _ -> object ["event_type" .= ev, "data" .= val]

