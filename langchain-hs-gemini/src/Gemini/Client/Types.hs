instance ToJSON Tool where
  toJSON = \case
    FunctionTool {..} ->
      object $
        [ "type" .= ("function" :: Text)
        , "name" .= functionName
        ]
          ++ catMaybes
            [ ("description" .=) <$> functionDescription
            , ("parameters" .=) <$> functionParameters
            ]
    GoogleSearchTool ->
      object ["type" .= ("google_search" :: Text)]
    GoogleMapsTool {..} ->
      object $
        ("type" .= ("google_maps" :: Text))
          : catMaybes
            [ ("latitude" .=) <$> mapsLatitude
            , ("longitude" .=) <$> mapsLongitude
            ]
    CodeExecutionTool ->
      object ["type" .= ("code_execution" :: Text)]
    FileSearchTool {..} ->
      object $
        ("type" .= ("file_search" :: Text))
          : catMaybes [("file_search_store_names" .=) <$> fileSearchStoreNames]
    UrlContextTool ->
      object ["type" .= ("url_context" :: Text)]

instance FromJSON Tool where
  parseJSON = withObject "Tool" $ \o -> do
    t <- o .: "type"
    case (t :: Text) of
      "function" -> do
        functionName <- o .: "name"
        functionDescription <- o .:? "description"
        functionParameters <- o .:? "parameters"
        pure FunctionTool {..}
      "google_search" -> pure GoogleSearchTool
      "google_maps" -> do
        mapsLatitude <- o .:? "latitude"
        mapsLongitude <- o .:? "longitude"
        pure GoogleMapsTool {..}
      "code_execution" -> pure CodeExecutionTool
      "file_search" -> do
        fileSearchStoreNames <- o .:? "file_search_store_names"
        pure FileSearchTool {..}
      "url_context" -> pure UrlContextTool
