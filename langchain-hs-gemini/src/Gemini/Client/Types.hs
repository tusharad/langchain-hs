      }
  | CodeExecutionTool
  | FileSearchTool
      { fileSearchStoreNames :: !(Maybe [Text])
      }
  | UrlContextTool
  deriving (Eq, Show, Generic)

-- | Construct a standard function tool.
functionTool :: Text -> Maybe Text -> Maybe Value -> Tool
