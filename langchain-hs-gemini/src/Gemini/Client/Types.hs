-- | Lifecycle status of an Interaction.
data InteractionStatus
  = StatusInProgress
  | StatusRequiresAction
  | StatusCompleted
  | StatusFailed
  | StatusCancelled
  | StatusIncomplete
  deriving (Eq, Show, Generic)

instance ToJSON InteractionStatus where
  toJSON = \case
    StatusInProgress -> "in_progress"
    StatusRequiresAction -> "requires_action"
    StatusCompleted -> "completed"
    StatusFailed -> "failed"
    StatusCancelled -> "cancelled"
    StatusIncomplete -> "incomplete"

instance FromJSON InteractionStatus where
  parseJSON = withText "InteractionStatus" $ \case
    "in_progress" -> pure StatusInProgress
    "requires_action" -> pure StatusRequiresAction
    "completed" -> pure StatusCompleted
    "failed" -> pure StatusFailed
    "cancelled" -> pure StatusCancelled
    "incomplete" -> pure StatusIncomplete
    other -> fail $ "Unknown InteractionStatus: " ++ T.unpack other

-- | An Interaction resource generated by Gemini.
data Interaction = Interaction
  { interactionId :: !Text
  , interactionObject :: !(Maybe Text)
  , interactionModel :: !(Maybe Text)
  , interactionAgent :: !(Maybe Text)
  , interactionStatus :: !InteractionStatus
  , interactionSteps :: ![Step]
  , interactionUsage :: !(Maybe Usage)
  , interactionCreated :: !(Maybe Text)
  , interactionUpdated :: !(Maybe Text)
  , interactionBackground :: !(Maybe Bool)
  , interactionStore :: !(Maybe Bool)
  , interactionStream :: !(Maybe Bool)
  , interactionSystemInstruction :: !(Maybe Text)
  , interactionTools :: !(Maybe [Tool])
  , interactionGenerationConfig :: !(Maybe GenerationConfig)
  , interactionResponseFormat :: !(Maybe ResponseFormat)
  , interactionPreviousInteractionId :: !(Maybe Text)
  , interactionErrors :: !(Maybe [ErrorDetail])
  }
  deriving (Eq, Show, Generic)

instance FromJSON Interaction where
  parseJSON = withObject "Interaction" $ \o -> do
    interactionId <- o .:? "id" .!= ""
    interactionObject <- o .:? "object"
    interactionModel <- o .:? "model"
    interactionAgent <- o .:? "agent"
    interactionStatus <- o .:? "status" .!= StatusCompleted
    interactionSteps <- o .:? "steps" .!= []
    interactionUsage <- o .:? "usage"
    interactionCreated <- o .:? "created"
    interactionUpdated <- o .:? "updated"
    interactionBackground <- o .:? "background"
    interactionStore <- o .:? "store"
    interactionStream <- o .:? "stream"
    interactionSystemInstruction <- o .:? "system_instruction"
    interactionTools <- o .:? "tools"
    interactionGenerationConfig <- o .:? "generation_config"
    interactionResponseFormat <- o .:? "response_format"
    interactionPreviousInteractionId <- o .:? "previous_interaction_id"
    interactionErrors <- o .:? "errors"
    pure Interaction {..}

instance ToJSON Interaction where
  toJSON Interaction {..} =
    object $
      catMaybes
        [ Just ("id" .= interactionId)
        , ("object" .=) <$> interactionObject
        , ("model" .=) <$> interactionModel
        , ("agent" .=) <$> interactionAgent
        , Just ("status" .= interactionStatus)
        , Just ("steps" .= interactionSteps)
        , ("usage" .=) <$> interactionUsage
        , ("created" .=) <$> interactionCreated
        , ("updated" .=) <$> interactionUpdated
        , ("background" .=) <$> interactionBackground
        , ("store" .=) <$> interactionStore
        , ("stream" .=) <$> interactionStream
        , ("system_instruction" .=) <$> interactionSystemInstruction
        , ("tools" .=) <$> interactionTools
        , ("generation_config" .=) <$> interactionGenerationConfig
        , ("response_format" .=) <$> interactionResponseFormat
        , ("previous_interaction_id" .=) <$> interactionPreviousInteractionId
        , ("errors" .=) <$> interactionErrors
        ]

